    when split_part(wp.word_id, ' — ', 1) like 'lv:%' then split_part(wp.word_id, ' — ', 1) || ' — ' || d.ru || ' (' || d.lv || ')'
    when split_part(wp.word_id, ' — ', 1) like 'lv_en:%' or split_part(wp.word_id, ' — ', 1) like 'lv-en:%' then split_part(wp.word_id, ' — ', 1) || ' — ' || d.ru || ' (' || d.lv || ' — ' || d.en || ')'
    when split_part(wp.word_id, ' — ', 1) like 'en_lv:%' or split_part(wp.word_id, ' — ', 1) like 'en-lv:%' then split_part(wp.word_id, ' — ', 1) || ' — ' || d.ru || ' (' || d.en || ' — ' || d.lv || ')'
    else split_part(wp.word_id, ' — ', 1) || ' — ' || d.ru || ' (' || d.en || ')'
  end
from dict d
where regexp_replace(split_part(wp.word_id, ' — ', 1), '^(lv:|lv_en:|lv-en:|en_lv:|en-lv:)', '') = d.id
  and not exists (
    select 1 from public.word_progress wp2
    where wp2.user_id = wp.user_id
      and wp2.word_id <> wp.word_id
      and split_part(wp2.word_id, ' — ', 1) = split_part(wp.word_id, ' — ', 1)
      and wp2.word_id like '% — %'
  );

delete from public.word_progress wp
where wp.word_id not like '% — %'
  and exists (
    select 1 from public.word_progress wp2
    where wp2.user_id = wp.user_id
      and wp2.word_id <> wp.word_id
      and split_part(wp2.word_id, ' — ', 1) = wp.word_id
      and wp2.word_id like '% — %'
  );

